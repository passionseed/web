/**
 * Portfolio guides at /port: the written versions of the Instagram Tips PDFs
 * (lib/content/tips-files.ts). A PDF of images can't be read by search engines
 * or AI answer engines, so each tip also lives here as plain text a student,
 * Google or ChatGPT can read and quote.
 *
 * Keep each guide faithful to its PDF. New advice belongs in the PDF first.
 * Copy rules: Thai first, no em dashes, never talk down (see PRODUCT.md).
 */

